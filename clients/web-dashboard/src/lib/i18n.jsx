const I18nContext = createContext(null);

function makeT(lang) {
  return (key, vars = {}) => {
    let str = translations[lang]?.[key] ?? translations[DEFAULT_LANG]?.[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
    return str;
  };
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && translations[stored]) return stored;
    return DEFAULT_LANG;
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key, vars = {}) => {
    let str = translations[lang]?.[key] ?? translations[DEFAULT_LANG]?.[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
    return str;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  // Graceful fallback outside a provider (unit tests render pages standalone):
  // behave as the default language instead of crashing.
  if (!ctx) return { lang: DEFAULT_LANG, setLang: () => {}, t: makeT(DEFAULT_LANG) };
  return ctx;
}
